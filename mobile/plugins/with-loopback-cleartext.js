// Expo config plugin: let RELEASE builds use plain HTTP to this device's loopback only.
//
// Why: the Mokhotsi API runs on the developer's PC and is reached over the USB cable
// (`adb reverse tcp:8000 tcp:8000`), which the phone sees as http://127.0.0.1:8000.
// Android blocks cleartext HTTP in release builds (debug builds opt out via
// `android:usesCleartextTraffic` in src/debug/AndroidManifest.xml), so a release build
// used for on-device evaluation could never sign in. This plugin adds a network
// security config to the RELEASE source set that permits cleartext to 127.0.0.1 and
// localhost while keeping every other host HTTPS-only — a real deployment must still
// use an HTTPS EXPO_PUBLIC_API_URL. Debug variants are untouched.
//
// It writes into android/app/src/release/, which `expo prebuild` does not generate,
// so nothing from the template is overwritten and prebuild --clean recreates it here.

const { withDangerousMod } = require("expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

const SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!-- @generated by mobile/plugins/with-loopback-cleartext.js -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">127.0.0.1</domain>
    <domain includeSubdomains="false">localhost</domain>
  </domain-config>
</network-security-config>
`;

const RELEASE_MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- @generated by mobile/plugins/with-loopback-cleartext.js -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
  <application android:networkSecurityConfig="@xml/network_security_config" />
</manifest>
`;

module.exports = function withLoopbackCleartext(config) {
  return withDangerousMod(config, [
    "android",
    (mod) => {
      const releaseDir = path.join(mod.modRequest.platformProjectRoot, "app", "src", "release");
      fs.mkdirSync(path.join(releaseDir, "res", "xml"), { recursive: true });
      fs.writeFileSync(path.join(releaseDir, "res", "xml", "network_security_config.xml"), SECURITY_CONFIG);
      fs.writeFileSync(path.join(releaseDir, "AndroidManifest.xml"), RELEASE_MANIFEST);
      return mod;
    },
  ]);
};
