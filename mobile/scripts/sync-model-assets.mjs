#!/usr/bin/env node
/**
 * Regenerates src/ml/modelAssets.generated.ts from assets/models/manifest.json.
 *
 * Metro resolves `require('x.tflite')` at bundle time and fails the whole bundle if the file
 * is missing. So only files that exist get a require(); missing ones are left out, and the
 * app reports them at runtime (ModelsUnavailableError) instead of failing to build.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modelsDir = join(root, 'assets', 'models');
const outFile = join(root, 'src', 'ml', 'modelAssets.generated.ts');

const manifest = JSON.parse(readFileSync(join(modelsDir, 'manifest.json'), 'utf8'));
const files = [manifest.detector?.file, manifest.embedder?.file].filter(Boolean);

const lines = files.map((file) =>
  existsSync(join(modelsDir, file))
    ? `  '${file}': require('../../assets/models/${file}'),`
    : `  // '${file}': missing — copy it into assets/models/ and run \`npm run models:sync\``,
);

const present = lines.filter((l) => !l.trimStart().startsWith('//')).length;
const source = `// AUTO-GENERATED by scripts/sync-model-assets.mjs — do not edit by hand.
/** Bundled .tflite assets keyed by manifest file name (Metro asset ids). */
export const MODEL_ASSETS: Readonly<Record<string, number | undefined>> = {
${lines.join('\n')}
};
`;

const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (previous !== source) {
  writeFileSync(outFile, source);
}
console.log(`models:sync → ${present}/${files.length} model files bundled`);
